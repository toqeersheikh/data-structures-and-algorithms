#include<iostream>
using namespace std;

int main()
{
	// Controlling Program Flow:
	
	// We have:
	
	// 1. Sequence: Ordering Statements sequentially
	
	
	// 2. Selection: Making decisions 
	
	
	// 3: Iteration: Looping or Repeating 
	
	// With these three components we can implement any algorithm:
	
	// . Sequence 
	// . Selection
	// . Iteration 
	
	
	// Selection: Decision Making 
	
	// if-statement 
	// if-else statement 
	// nested if statement 
	// Switch statement 
	// Conditional Operator : if else wrapped in an operator 
	
	// Iteration - Looping 
	
	// . for loop
	// . range based for loop
	// . while loop
	// . do while loop
	// . infinite loops 
	// . nested loops
	// . continue and break statements
	
	// If statement 
	
	// if(condition) {code block}
	
	if (100==100) cout<<"True"<<endl;
	
	// We can nest if inside if block 
	
	// if we have nested if statement and a single else block then we may face a problem called:
	
	// Dangling else problem 
	
	// Every language has its own way to handle this problem 
	
	// in c++ an else belongs to the closest if statement 
	
	// And of course we can use blocks to achieve any logic 
	
	
	return 0;
}